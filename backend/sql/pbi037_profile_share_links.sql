CREATE TABLE IF NOT EXISTS ita.profile_share_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES ita.users(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 allowed_fields JSONB NOT NULL DEFAULT '[]'::jsonb,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 revoked_at TIMESTAMPTZ NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_profile_share_links_user_id ON ita.profile_share_links(user_id);
